/**
 * Writes src/styles/theme-default.css: the scales for DEFAULT_ACCENT_SEED, so the kit renders
 * correctly before ThemeProvider injects the user's theme. Run: pnpm --filter @psyche/ui gen:theme
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { themeToCss } from "../src/theme/css.ts";
import { DEFAULT_ACCENT_SEED, generateTheme } from "../src/theme/generate.ts";

const out = fileURLToPath(new URL("../src/styles/theme-default.css", import.meta.url));
const header = `/* Generated by scripts/gen-default-theme.ts from ${DEFAULT_ACCENT_SEED}. Do not edit. */\n`;
writeFileSync(out, header + themeToCss(generateTheme({ accentSeed: DEFAULT_ACCENT_SEED })));
console.warn(`wrote ${out}`);

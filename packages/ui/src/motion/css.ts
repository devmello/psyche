import { duration, ease, routeRisePx, type SpringToken, spring, springPhysics } from "./tokens.ts";

/**
 * CSS forms of the motion tokens (docs/design/motion.md §2.4): durations, easing curves and
 * springs sampled into `linear()` easings. CSS cannot hand off velocity, so these springs are
 * for transitions that are rarely interrupted (popovers, dialogs, sheets); Motion handles the
 * rest. `pnpm --filter @psyche/ui gen:motion` writes the output to `styles/motion.css`.
 */

/** Time (s) for a unit step to settle within 0.1% (position and velocity). */
export function settleTime(s: SpringToken): number {
  const { stiffness: k, damping: c } = springPhysics(s);
  let x = 0;
  let v = 0;
  let last = 0;
  const dt = 1 / 4000;
  for (let t = 0; t < 3; t += dt) {
    const a = -k * (x - 1) - c * v;
    v += a * dt;
    x += v * dt;
    if (Math.abs(x - 1) > 0.001 || Math.abs(v) > 0.01) last = t;
  }
  return last;
}

/** The spring's step response as a CSS `linear()` easing with `points` stops. */
export function springLinear(s: SpringToken, points = 32): string {
  const { stiffness: k, damping: c } = springPhysics(s);
  const total = settleTime(s);
  const dt = 1 / 4000;
  const stops: string[] = [];
  let x = 0;
  let v = 0;
  let t = 0;
  for (let i = 0; i <= points; i++) {
    const target = (total * i) / points;
    while (t < target) {
      const a = -k * (x - 1) - c * v;
      v += a * dt;
      x += v * dt;
      t += dt;
    }
    stops.push(i === points ? "1" : String(Math.round(x * 10000) / 10000));
  }
  return `linear(${stops.join(", ")})`;
}

const bezier = (p: readonly number[]) => `cubic-bezier(${p.join(", ")})`;

export function motionCss(): string {
  const lines: string[] = [
    "/* Generated by scripts/gen-motion.ts from src/motion/tokens.ts. Do not edit. */",
    ":root {",
  ];
  for (const name of ["instant", "micro", "short", "medium", "long"] as const) {
    lines.push(`  --duration-${name}: ${duration[name]}ms;`);
    lines.push(`  --duration-${name}-exit: ${Math.round(duration[name] * duration.exitFactor)}ms;`);
  }
  for (const [name, css] of [
    ["route", "route"],
    ["routeReduced", "route-reduced"],
    ["splashDelay", "splash-delay"],
    ["lantern", "lantern"],
    ["lanternDelay", "lantern-delay"],
  ] as const)
    lines.push(`  --duration-${css}: ${duration[name]}ms;`);
  lines.push(`  --route-rise: ${routeRisePx}px;`);
  lines.push("  --ease-linear: linear;");
  for (const [name, p] of Object.entries(ease)) lines.push(`  --ease-${name}: ${bezier(p)};`);
  for (const [name, s] of Object.entries(spring)) {
    lines.push(`  --spring-${name}: ${springLinear(s)};`);
    lines.push(`  --spring-${name}-duration: ${Math.round(settleTime(s) * 1000)}ms;`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

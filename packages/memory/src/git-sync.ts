import { execFile } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { isAbsolute, join } from "node:path";
import { promisify } from "node:util";
import { PsycheError } from "@psyche/protocol";
import { blockingKinds } from "./filters.ts";
import type { SqliteMemoryStore } from "./store.ts";

/**
 * Git-friendly workspace (feature H10; OpenClaw): optional sync of `$PSYCHE_HOME/workspace` to
 * the owner's own private repository. Backs `psyche workspace sync` (CLI, S22).
 *
 * - Runs the system `git` with `execFile` (never a shell), `GIT_TERMINAL_PROMPT=0` so a missing
 *   credential fails instead of hanging, and the owner's own git credentials (SSH agent or a
 *   credential helper). Psyche never stores a git secret.
 * - Writes a generated `.gitignore` (temp files, OS junk, raw imports from other assistants).
 * - Pushing sends memory off the machine, so every file about to be committed is scanned first
 *   and a credential or card number stops the sync (security §8; shared rules).
 * - Remotes must be `https://`, `ssh://`, `user@host:path` or a local path, never with a
 *   password in the URL.
 * - Pulls with rebase before pushing; a conflict aborts the rebase and is reported, nothing is
 *   forced. Pulled changes are the owner's own edits and are reindexed through `store.sync()`.
 * - Only the owner starts a sync (CLI or a paired device); there is no agent tool for it.
 */

const run = promisify(execFile);

export const GITIGNORE = `# Generated by Psyche (workspace sync). Edit freely; Psyche only adds missing lines.
.DS_Store
Thumbs.db
*.tmp
.*.tmp
*.swp
*~
# Raw exports from other assistants stay on this machine.
memory/imports/
`;

const AUTHOR = ["-c", "user.name=Psyche", "-c", "user.email=psyche@localhost"];

export interface GitSyncOptions {
  /** Remote name (default `origin`). */
  remote?: string;
  /** Branch (default `main`). */
  branch?: string;
  /** Commit only; do not pull or push. */
  localOnly?: boolean;
  /** Path to the git binary (default `git` on PATH). */
  gitPath?: string;
}

export interface GitSyncResult {
  committed: boolean;
  commit?: string;
  pulled: boolean;
  pushed: boolean;
  /** Files with rebase conflicts (the rebase was aborted; nothing was pushed). */
  conflicts?: string[];
}

/** Accepts the owner's remote URL forms; refuses plain http and embedded credentials. */
export function validateRemoteUrl(url: string): string {
  const u = url.trim();
  if (u.length === 0 || u.length > 2048 || /[\s\0]/.test(u) || u.startsWith("-")) {
    throw new PsycheError("invalid_params", "invalid git remote");
  }
  if (/^https:\/\//i.test(u) || /^ssh:\/\//i.test(u)) {
    let parsed: URL;
    try {
      parsed = new URL(u);
    } catch {
      throw new PsycheError("invalid_params", "invalid git remote");
    }
    if (parsed.password !== "" || (parsed.protocol === "https:" && parsed.username !== "")) {
      throw new PsycheError(
        "invalid_params",
        "remote URLs must not contain credentials; use an SSH key or a git credential helper",
      );
    }
    return u;
  }
  if (/^[A-Za-z0-9._-]+@[A-Za-z0-9.-]+:[^\s]+$/.test(u)) return u; // scp-like SSH
  if (isAbsolute(u)) return u; // a local or mounted bare repository
  throw new PsycheError(
    "invalid_params",
    "use an https://, ssh://, user@host:path or local path remote",
  );
}

export class WorkspaceGit {
  readonly #store: SqliteMemoryStore;
  readonly #git: string;

  constructor(store: SqliteMemoryStore, options: { gitPath?: string } = {}) {
    this.#store = store;
    this.#git = options.gitPath ?? "git";
  }

  async #run(args: string[], allowFail = false): Promise<{ stdout: string; code: number }> {
    try {
      const { stdout } = await run(this.#git, args, {
        cwd: this.#store.root,
        env: { ...process.env, GIT_TERMINAL_PROMPT: "0", GIT_ASKPASS: "", LC_ALL: "C" },
        maxBuffer: 16 * 1024 * 1024,
        timeout: 120_000,
      });
      return { stdout, code: 0 };
    } catch (err) {
      const e = err as { code?: unknown; stdout?: string; stderr?: string };
      if (e.code === "ENOENT") throw new PsycheError("unavailable", "git is not installed");
      if (allowFail)
        return { stdout: e.stdout ?? "", code: typeof e.code === "number" ? e.code : 1 };
      // stderr can echo a remote URL; it never contains a secret because remotes cannot hold one.
      throw new PsycheError(
        "unavailable",
        `git ${args[0] ?? ""} failed: ${(e.stderr ?? "").trim().slice(0, 300)}`,
      );
    }
  }

  get isRepo(): boolean {
    return existsSync(join(this.#store.root, ".git"));
  }

  /** `git init` on `branch` and a generated `.gitignore` (missing lines are added, never removed). */
  async init(branch = "main"): Promise<void> {
    if (!this.isRepo) await this.#run(["init", "-q", "-b", branch]);
    const path = join(this.#store.root, ".gitignore");
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    const have = new Set(current.split("\n").map((l) => l.trim()));
    const missing = GITIGNORE.split("\n").filter((l) => l.trim().length > 0 && !have.has(l.trim()));
    if (current === "") writeFileSync(path, GITIGNORE, { mode: 0o600 });
    else if (missing.length > 0) {
      writeFileSync(path, `${current.replace(/\n*$/, "\n")}${missing.join("\n")}\n`, {
        mode: 0o600,
      });
    }
  }

  /** Sets (or replaces) the remote URL after validating it. */
  async setRemote(url: string, remote = "origin"): Promise<void> {
    const valid = validateRemoteUrl(url);
    if (!/^[A-Za-z0-9._-]+$/.test(remote))
      throw new PsycheError("invalid_params", "invalid remote name");
    await this.init();
    const has = (await this.#run(["remote"], true)).stdout.split("\n").includes(remote);
    await this.#run(has ? ["remote", "set-url", remote, valid] : ["remote", "add", remote, valid]);
  }

  /** Files git would commit, relative to the workspace. */
  async #pending(): Promise<string[]> {
    const { stdout } = await this.#run(["status", "--porcelain", "-z", "--untracked-files=all"]);
    return stdout
      .split("\0")
      .filter((e) => e.length > 3)
      .map((e) => e.slice(3))
      .filter((p) => existsSync(join(this.#store.root, p)));
  }

  /** Refuses the sync if any file to be committed holds a credential or card number. */
  #scan(paths: readonly string[]): void {
    const flagged = paths.filter((p) => {
      try {
        return blockingKinds(readFileSync(join(this.#store.root, p), "utf8"), true).length > 0;
      } catch {
        return false;
      }
    });
    if (flagged.length > 0) {
      throw new PsycheError(
        "policy_denied",
        `not syncing: ${flagged.join(", ")} looks like it holds a credential or card number`,
        { details: { files: flagged } },
      );
    }
  }

  async sync(options: GitSyncOptions = {}): Promise<GitSyncResult> {
    const remote = options.remote ?? "origin";
    const branch = options.branch ?? "main";
    if (!/^[A-Za-z0-9._/-]+$/.test(branch) || branch.startsWith("-")) {
      throw new PsycheError("invalid_params", "invalid branch name");
    }
    await this.init(branch);
    await this.#store.idle();
    const pending = await this.#pending();
    this.#scan(pending);
    const result: GitSyncResult = { committed: false, pulled: false, pushed: false };
    if (pending.length > 0) {
      await this.#run(["add", "-A"]);
      await this.#run([
        ...AUTHOR,
        "commit",
        "-q",
        "-m",
        `Psyche memory sync ${this.#store.now().date}`,
      ]);
      result.committed = true;
      result.commit = (await this.#run(["rev-parse", "HEAD"])).stdout.trim();
    }
    if (options.localOnly === true) return result;
    const remotes = (await this.#run(["remote"], true)).stdout.split("\n");
    if (!remotes.includes(remote)) {
      throw new PsycheError("invalid_params", `no remote ${remote}; set one with setRemote(url)`);
    }
    const fetched = await this.#run(["fetch", "-q", remote, branch], true);
    const hasRemoteBranch =
      fetched.code === 0 &&
      (await this.#run(["rev-parse", "--verify", "-q", `${remote}/${branch}`], true)).code === 0;
    if (hasRemoteBranch) {
      const behind = Number(
        (await this.#run(["rev-list", "--count", `HEAD..${remote}/${branch}`])).stdout.trim(),
      );
      if (behind > 0) {
        const rebased = await this.#run([...AUTHOR, "rebase", "-q", `${remote}/${branch}`], true);
        if (rebased.code !== 0) {
          const { stdout } = await this.#run(["diff", "--name-only", "--diff-filter=U"], true);
          await this.#run(["rebase", "--abort"], true);
          result.conflicts = stdout.split("\n").filter(Boolean);
          return result;
        }
        result.pulled = true;
        await this.#store.sync();
      }
    }
    await this.#run(["push", "-q", remote, `HEAD:refs/heads/${branch}`]);
    result.pushed = true;
    return result;
  }
}

    "npx -p pkg@1.2.3 -p other server",
    "npx --package=pkg server",
    "npx -c 'pkg@1.2.3 run'",
    "npx",
    "/usr/local/bin/npx -y pkg",
    "C:\\Program Files\\nodejs\\npx.cmd -y pkg",
    "pnpx pkg",
    "pnpm dlx pkg",
    "pnpm dlx --package=pkg@^2 server",

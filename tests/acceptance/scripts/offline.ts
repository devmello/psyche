#!/usr/bin/env -S node --experimental-strip-types
/**
 * `pnpm --filter @psyche/acceptance-tests offline`: the whole offline acceptance pass, then the
 * scorecard.
 *
 * 1. the acceptance suite with model-visible capture on (scenarios, injection corpus in three
 *    modes, resumability sweep, performance budgets, the live driver's plumbing, accessibility);
 * 2. `pnpm check:secrets --captures <dir> --require-captures` over everything those runs showed a
 *    model, a transcript, a log, a card or a receipt;
 * 3. SCORECARD.md regenerated from out/acceptance/*.json and any live reports present.
 *
 *   tsx scripts/offline.ts [--scorecard-only] [--captures <dir>]
 */
import { execFileSync, spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = resolve(fileURLToPath(new URL(".", import.meta.url)));
const PKG = resolve(HERE, "..");
const ROOT = resolve(PKG, "../..");
const OUT = join(ROOT, "out/acceptance");

type Json = Record<string, unknown>;

function read(name: string): Json | undefined {
  const p = join(OUT, `${name}.json`);
  return existsSync(p) ? (JSON.parse(readFileSync(p, "utf8")) as Json) : undefined;
}

function run(cmd: string, args: string[], env: Record<string, string> = {}): number {
  process.stdout.write(`\n$ ${cmd} ${args.join(" ")}\n`);
  const r = spawnSync(cmd, args, { cwd: ROOT, stdio: "inherit", env: { ...process.env, ...env } });
  return r.status ?? 1;
}

function sha(): string {
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      cwd: ROOT,
      encoding: "utf8",
    }).trim();
  } catch {
    return "unknown";
  }
}

const mark = (ok: boolean | undefined) => (ok === undefined ? "not run" : ok ? "pass" : "FAIL");

/** The scorecard: one row per check, with the evidence file next to it. */
function scorecard(secrets: { ok: boolean; captures: number } | undefined): string {
  const scenarios = read("scenarios");
  const injection = read("injection");
  const resumability = read("resumability");
  const scenariosM2 = read("scenarios-m2");
  const perf = read("perf");
  const a11y = read("a11y");
  const lives = readdirSync(existsSync(OUT) ? OUT : PKG)
    .filter((f) => f.startsWith("live-") && f.endsWith(".json"))
    .map((f) => JSON.parse(readFileSync(join(OUT, f), "utf8")) as Json);
  const lines: string[] = [];
  const L = (s = "") => lines.push(s);

  L("# Milestone 1–3 acceptance scorecard");
  L();
  L(
    `Generated by \`pnpm --filter @psyche/acceptance-tests offline\` at \`${sha()}\`. Evidence: \`out/acceptance/*.json\` (git-ignored; rerun to regenerate). Criteria: docs/03 "Cross-cutting acceptance criteria", docs/08 Milestones 1 and 2. Owner triage and the narrative: docs/status/int-3.md.`,
  );
  L();
  L(
    "Where these run: since 2026-10-19 (prompts/_shared-rules.md \"Merge gate\") a PR merges on a local gate (typecheck, the touched packages' tests, biome). Per-PR CI is a fast lint and typecheck; the full suites, including this package and the `security` workflow's scenario, injection, secret-leak and resumability jobs, run on pushes to main and nightly. Breakage found there is logged in docs/status/known-red.md.",
  );
  L();
  L("## Offline checks (scripted provider, fixtures, no network)");
  L();
  L("| Check | Result | Detail |");
  L("| --- | --- | --- |");
  for (const s of ((scenarios?.scenarios as Json[] | undefined) ?? []) as {
    scenario: string;
    hard: { pass: number; fail: number };
    soft: { pass: number; fail: number };
    known: { id: string; issue: string }[];
    unexpected: string[];
  }[]) {
    const ok = s.unexpected.length === 0;
    const known =
      s.known.length === 0
        ? ""
        : `; known: ${s.known.map((k) => `${k.id} (${k.issue.replace(/.*\//, "#")})`).join(", ")}`;
    L(
      `| Scenario ${s.scenario}, scripted | ${mark(ok)} | hard ${s.hard.pass}/${s.hard.pass + s.hard.fail}, soft ${s.soft.pass}/${s.soft.pass + s.soft.fail}${known} |`,
    );
  }
  const stacks = (injection?.stacks as Record<string, Json> | undefined) ?? {};
  const corpus = injection?.corpus as { committedCases: number; exampleCases: number } | undefined;
  for (const [name, st] of Object.entries(stacks)) {
    const byMode = st.byMode as Record<
      string,
      {
        runs: number;
        pass: number;
        warn: number;
        fail: number;
        error: number;
        executed: string[];
        failures: string[];
        known?: string[];
      }
    >;
    for (const [mode, m] of Object.entries(byMode)) {
      const known = m.known ?? [];
      const ok = m.failures.length === 0 && m.error === 0 && m.executed.length === 0;
      const note = known.length === 0 ? "" : `; known: ${known.join("; ")}`;
      L(
        `| Injection corpus, ${mode}, ${name} stack | ${mark(ok)} | ${m.runs} runs: ${m.pass} pass, ${m.warn} warn, ${m.fail} fail, ${m.error} error; executed: ${m.executed.length}${note} |`,
      );
    }
  }
  if (corpus !== undefined)
    L(
      `| Injection corpus size | ${corpus.committedCases >= 150 ? "pass" : "BLOCKED"} | ${corpus.committedCases} committed cases (target 150, docs/status/s18.md) + ${corpus.exampleCases} worked example |`,
    );
  L(
    `| Secret-leak checker over captured model-visible text | ${mark(secrets?.ok)} | ${secrets === undefined ? "run `pnpm --filter @psyche/acceptance-tests offline`" : `${secrets.captures} capture files, 0 hits`} |`,
  );
  for (const s of ((resumability?.scenarios as Json[] | undefined) ?? []) as {
    scenario: string;
    killPoints: number;
    sampled: number;
    baseline: { ok: boolean };
    results: { violations: string[]; outcome: string }[];
  }[]) {
    const ok = s.baseline.ok && s.results.every((r) => r.violations.length === 0);
    const outcomes = [...new Set(s.results.map((r) => r.outcome))].join(", ");
    L(
      `| Resumability, ${s.scenario} (real stack) | ${mark(ok)} | ${s.sampled} of ${s.killPoints} kill points, 0 violations; outcomes: ${outcomes} |`,
    );
  }
  if (resumability !== undefined)
    L(
      `| Resumability total | ${mark(resumability.ok as boolean)} | ${resumability.total} random kill points: ${resumability.milestone1 ?? resumability.total} across V1, V2, V3, V4, V7${resumability.milestone2 === undefined ? "" : ` and ${resumability.milestone2} across V5, V6, V8, V9`} |`,
    );
  L();
  L("## Milestone 2 scenarios (scripted)");
  L();
  L(
    "Authored by INT-3 in S18's format under `tests/acceptance/scenarios-m2` (validated by `tests/scenarios/validate.mjs --dir`). Real agent loop, broker and audit; the real documents pipeline (V5) and agent-core's `task.start` / `schedule` built-ins (V8, V9); tools without an agent registration on main are provisional fakes (`tests/acceptance/scenarios-m2/README.md`).",
  );
  L();
  L("| Scenario | Result | Detail |");
  L("| --- | --- | --- |");
  for (const s of ((scenariosM2?.scenarios as Json[] | undefined) ?? []) as {
    scenario: string;
    hard: { pass: number; fail: number };
    soft: { pass: number; fail: number };
    known: { id: string; issue: string }[];
    unexpected: string[];
  }[]) {
    const known =
      s.known.length === 0
        ? ""
        : `; known: ${s.known.map((k) => `${k.id} (${k.issue})`).join(", ")}`;
    L(
      `| ${s.scenario} | ${mark(s.unexpected.length === 0)} | hard ${s.hard.pass}/${s.hard.pass + s.hard.fail}, soft ${s.soft.pass}/${s.soft.pass + s.soft.fail}${known} |`,
    );
  }
  if (scenariosM2 === undefined) L("| V5, V6, V8, V9 | not run | run the offline pass |");
  L();
  L("## Performance budgets");
  L();
  const t = (perf?.timings as Record<string, number> | undefined) ?? {};
  const b = (perf?.budgets as Record<string, number> | undefined) ?? {};
  L("| Budget (docs/03) | Measured | Result |");
  L("| --- | --- | --- |");
  L(
    `| Cold start to first token < ${b.coldStartToFirstTokenMs ?? 3000} ms (hosted model) | ${t.coldStartToFirstDeltaMs ?? "?"} ms with the scripted provider (boot ${t.gatewayBootMs ?? "?"} ms + first delta ${t.firstDeltaMs ?? "?"} ms); hosted model: needs live model | ${perf === undefined ? "not run" : "pass (Gateway overhead); needs live model"} |`,
  );
  L(
    `| Browser snapshot < ${b.browserSnapshotMs ?? 300} ms (typical page) | ${t.browserSnapshotMs ?? "?"} ms median, ${t.browserSnapshotRefs ?? "?"}-ref page over the CDP bridge mock | ${perf === undefined ? "not run" : mark((t.browserSnapshotMs ?? 1e9) < (b.browserSnapshotMs ?? 300))} |`,
  );
  L(
    `| Memory search < ${b.memorySearchMs ?? 100} ms | ${t.memorySearchMs ?? "?"} ms median over ${t.memorySearchCorpus ?? "?"} chunks | ${perf === undefined ? "not run" : mark((t.memorySearchMs ?? 1e9) < (b.memorySearchMs ?? 100))} |`,
  );
  L();
  L(`Machine: ${perf?.machine ?? "?"}.`);
  L();
  L("## Accessibility (main flows as the desktop renders them)");
  L();
  L("| Check | Result | Detail |");
  L("| --- | --- | --- |");
  const a = (a11y ?? {}) as { ok?: boolean; tests?: number; failed?: number };
  L(
    `| axe-core on approval card, question card, checklist, wrap-up, chat screen, onboarding, rail | ${mark(a.ok)} | ${a.tests ?? "?"} tests, ${a.failed ?? "?"} failed (jsdom; contrast gated by the theme generator) |`,
  );
  L(
    `| Keyboard: card focus, Return never approves, ⌘Return / ⌘D, Tab order through dock and composer, question answers, onboarding Next | ${mark(a.ok)} | tests/acceptance/a11y/main-flows.test.tsx |`,
  );
  L(
    `| Reduced motion: \`prefers-reduced-motion\` and the explicit setting | ${mark(a.ok)} | data-reduce-motion on the root; kit and shell stylesheets zero animations |`,
  );
  L(
    "| VoiceOver walk-through (rotor, announcements) | manual: not run | needs a person with VoiceOver on the packaged app |",
  );
  L();
  L("## Live gates (real model, three runs per scenario)");
  L();
  L("| Model | V1 inbox triage | V2 calendar planning | V7 research brief |");
  L("| --- | --- | --- | --- |");
  const cell = (live: Json | undefined, scenario: string) => {
    if (live === undefined) return "not run: key needed";
    const rs = (
      live.runs as {
        scenario: string;
        ok: boolean;
        summary: { hard: { unchecked: number }; soft: { pass: number; fail: number } };
      }[]
    ).filter((r) => r.scenario === scenario);
    if (rs.length === 0) return "not run";
    const ok = rs.filter((r) => r.ok).length;
    const soft = rs.reduce((n, r) => n + r.summary.soft.pass, 0);
    const softAll = rs.reduce((n, r) => n + r.summary.soft.pass + r.summary.soft.fail, 0);
    const unchecked = rs.reduce((n, r) => n + r.summary.hard.unchecked, 0);
    return `${ok}/${rs.length} hard-clean, soft ${soft}/${softAll}${unchecked > 0 ? `, ${unchecked} hard unchecked` : ""}`;
  };
  const byModel = new Map(lives.map((l) => [String(l.model), l]));
  const expected = ["anthropic (hosted)", "openai (hosted)", "ollama (local, agent-capable)"];
  for (const label of expected) {
    const provider = label.split(" ")[0] as string;
    const live = [...byModel.entries()].find(([m]) => m.startsWith(`${provider}/`))?.[1];
    const name = live === undefined ? label : String(live.model);
    L(
      `| ${name} | ${cell(live, "v1-inbox-triage")} | ${cell(live, "v2-calendar-planning")} | ${cell(live, "v7-research-brief")} |`,
    );
  }
  L();
  L(
    "Run: `PSYCHE_LIVE_TESTS=1 PSYCHE_MODEL=<provider>/<model> <KEY>=… pnpm --filter @psyche/acceptance-tests live` (keys: tests/acceptance/README.md).",
  );
  L();
  return `${lines.join("\n")}\n`;
}

function main(argv: string[]): number {
  const arg = (name: string) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  let secrets: { ok: boolean; captures: number } | undefined;
  if (!argv.includes("--scorecard-only")) {
    const captures =
      arg("--captures") ?? mkdtempSync(join(tmpdir(), "psyche-acceptance-captures-"));
    mkdirSync(captures, { recursive: true });
    mkdirSync(OUT, { recursive: true });
    const suite = run(
      "pnpm",
      [
        "--filter",
        "@psyche/acceptance-tests",
        "exec",
        "vitest",
        "run",
        "--reporter=default",
        "--reporter=json",
        "--outputFile",
        join(OUT, "vitest.json"),
      ],
      {
        PSYCHE_CAPTURE_DIR: captures,
      },
    );
    // The accessibility summary comes from vitest's JSON report.
    try {
      const v = JSON.parse(readFileSync(join(OUT, "vitest.json"), "utf8")) as {
        testResults: { name: string; assertionResults: { status: string }[] }[];
      };
      const a11y = v.testResults.filter((f) => f.name.includes("/a11y/"));
      const tests = a11y.flatMap((f) => f.assertionResults);
      writeFileSync(
        join(OUT, "a11y.json"),
        `${JSON.stringify({ ok: tests.length > 0 && tests.every((t) => t.status === "passed"), tests: tests.length, failed: tests.filter((t) => t.status !== "passed").length }, null, 2)}\n`,
      );
    } catch {
      // no report: the suite did not run
    }
    const files = existsSync(captures) ? readdirSync(captures).length : 0;
    const leak = run("pnpm", ["check:secrets", "--captures", captures, "--require-captures"]);
    secrets = { ok: leak === 0, captures: files };
    if (suite !== 0 || leak !== 0) process.exitCode = 1;
  }
  const md = scorecard(secrets);
  writeFileSync(join(PKG, "SCORECARD.md"), md);
  process.stdout.write(`\nwrote tests/acceptance/SCORECARD.md\n`);
  // process.exitCode is typed string | number | undefined in recent @types/node.
  return Number(process.exitCode ?? 0);
}

const entry = process.argv[1];
if (entry !== undefined && import.meta.url === pathToFileURL(entry).href) {
  process.exit(main(process.argv.slice(2)));
}
